"""Turn docs/openapi.json into TypeScript types. Standard library only.

The converter handles exactly the JSON Schema subset the VYRON contract uses and raises
``UnsupportedSchema`` for anything else, so a new keyword can never silently become ``unknown``.
The output is plain TypeScript with no imports; ``tsc`` checks it in tests/test_typescript.py.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

HEADER = "GENERATED by scripts/generate_ts_types.py from docs/openapi.json. Do not edit."
RENAMES = {"Error": "ApiError"}  # `Error` would shadow the global
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_PRIMITIVES = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}
_IGNORED = {
    "description", "title", "format", "default", "minimum", "maximum", "minLength", "maxLength", "pattern",
    "minItems", "maxItems", "maxProperties", "uniqueItems", "style", "explode", "example", "examples", "deprecated",
}  # fmt: skip
_STRUCTURAL = {"type", "enum", "const", "items", "properties", "required", "additionalProperties", "$ref"}


class UnsupportedSchema(ValueError):
    pass


def type_name(schema_name: str) -> str:
    return RENAMES.get(schema_name, schema_name)


def prop_key(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name)


def _literal(value: Any) -> str:
    if isinstance(value, (str, int, float, bool)) or value is None:
        return json.dumps(value)
    raise UnsupportedSchema(f"unsupported literal: {value!r}")


def constraints(schema: dict[str, Any]) -> str:
    """A short human-readable summary of the validation keywords (for JSDoc)."""
    parts: list[str] = []
    if "format" in schema:
        parts.append(f"format {schema['format']}")
    if "pattern" in schema:
        parts.append(f"pattern {schema['pattern']}")
    if "minLength" in schema or "maxLength" in schema:
        parts.append(f"length {schema.get('minLength', 0)}-{schema.get('maxLength', '∞')}")
    if "minimum" in schema or "maximum" in schema:
        parts.append(f"range {schema.get('minimum', '-∞')}..{schema.get('maximum', '∞')}")
    if "minItems" in schema or "maxItems" in schema:
        parts.append(f"items {schema.get('minItems', 0)}-{schema.get('maxItems', '∞')}")
    if "maxProperties" in schema:
        parts.append(f"at most {schema['maxProperties']} properties")
    if schema.get("uniqueItems"):
        parts.append("unique")
    if "default" in schema:
        parts.append(f"default {json.dumps(schema['default'])}")
    return "; ".join(parts)


def doc_comment(schema: dict[str, Any], indent: str = "") -> str:
    text = " ".join(
        part for part in (str(schema.get("description", "")).strip(), constraints(schema)) if part
    ).replace("*/", "*\\/")
    return f"{indent}/** {text} */\n" if text else ""


def _nullable_other(schema: dict[str, Any]) -> dict[str, Any] | None:
    """The schema ``X`` of ``{"anyOf": [X, {"type": "null"}]}`` (either order), or None for any other shape.

    This is the one ``anyOf`` the contract uses (``nullable()`` in the API's schemas, for a reference); every
    other ``anyOf`` is still refused so a new union can never silently become something else.
    """
    options = schema.get("anyOf")
    if not isinstance(options, list) or len(options) != 2:
        return None
    nulls = [o for o in options if isinstance(o, dict) and o == {"type": "null"}]
    others = [o for o in options if isinstance(o, dict) and o != {"type": "null"}]
    if len(nulls) != 1 or len(others) != 1 or set(schema) - {"anyOf"} - _IGNORED:
        return None
    return others[0]


def ts_type(schema: dict[str, Any], indent: str = "") -> str:
    if "anyOf" in schema:
        other = _nullable_other(schema)
        if other is None:
            raise UnsupportedSchema(f"only 'a schema or null' is supported for anyOf: {json.dumps(schema)[:120]}")
        return f"{ts_type(other, indent)} | null"
    unknown = set(schema) - _STRUCTURAL - _IGNORED
    if unknown and not all(k.startswith("x-") for k in unknown):
        raise UnsupportedSchema(f"unsupported schema keywords {sorted(unknown)} in {json.dumps(schema)[:120]}")
    if "$ref" in schema:
        return type_name(schema["$ref"].rsplit("/", 1)[1])
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(v) for v in schema["enum"])
    kinds = schema.get("type")
    if kinds is None:
        raise UnsupportedSchema(f"schema without a type: {json.dumps(schema)[:120]}")
    names = [kinds] if isinstance(kinds, str) else list(kinds)
    rendered: list[str] = []
    for name in names:
        if name in _PRIMITIVES:
            rendered.append(_PRIMITIVES[name])
        elif name == "array":
            if "items" not in schema:
                raise UnsupportedSchema("array without items")
            rendered.append(f"ReadonlyArray<{ts_type(schema['items'], indent)}>")
        elif name == "object":
            rendered.append(_object(schema, indent))
        else:
            raise UnsupportedSchema(f"unsupported type {name!r}")
    return " | ".join(rendered)


def _object(schema: dict[str, Any], indent: str) -> str:
    properties = schema.get("properties")
    extra = schema.get("additionalProperties")
    if properties is None:
        if isinstance(extra, dict):
            return f"Record<string, {ts_type(extra, indent)}>"
        raise UnsupportedSchema("object without properties or a typed additionalProperties")
    if extra not in (False, None):
        raise UnsupportedSchema("objects that mix properties and additionalProperties are not supported")
    required = set(schema.get("required", []))
    inner = indent + "  "
    lines = ["{"]
    for name, sub in properties.items():
        optional = "" if name in required else "?"
        lines.append(f"{doc_comment(sub, inner)}{inner}{prop_key(name)}{optional}: {ts_type(sub, inner)};".rstrip("\n"))
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def _screaming(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name.replace("GitHub", "Github")).upper()


def render_schema(name: str, schema: dict[str, Any]) -> str:
    out = doc_comment(schema)
    tname = type_name(name)
    if "enum" in schema and schema.get("type") == "string":
        values = ", ".join(json.dumps(v) for v in schema["enum"])
        const = f"{_screaming(tname)}_VALUES"
        out += f"export const {const} = [{values}] as const;\n"
        out += f"export type {tname} = (typeof {const})[number];\n"
        return out
    body = ts_type(schema)
    if schema.get("type") == "object" and "properties" in schema:
        return out + f"export interface {tname} {body}\n"
    return out + f"export type {tname} = {body};\n"


def _success(operation: dict[str, Any]) -> tuple[str, str]:
    for status, response in operation["responses"].items():
        if status.startswith("2"):
            content = response.get("content", {}).get("application/json")
            return status, (ts_type(content["schema"]) if content else "undefined")
    raise UnsupportedSchema(f"{operation['operationId']} has no success response")


def _params(operation: dict[str, Any], location: str, indent: str = "    ") -> str:
    items = [p for p in operation.get("parameters", []) if p["in"] == location]
    if not items:
        return "Record<never, never>"
    inner = indent + "  "
    lines = ["{"]
    for p in items:
        optional = "" if p.get("required") else "?"
        comment = doc_comment({**p["schema"], "description": p.get("description", "")}, inner)
        lines.append(f"{comment}{inner}{prop_key(p['name'])}{optional}: {ts_type(p['schema'], inner)};".rstrip("\n"))
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def render_operations(spec: dict[str, Any]) -> str:
    entries: list[str] = []
    routes: list[str] = []
    for path, item in spec["paths"].items():
        for method, operation in item.items():
            op_id = operation["operationId"]
            status, response = _success(operation)
            body = "undefined"
            if "requestBody" in operation:
                body = ts_type(operation["requestBody"]["content"]["application/json"]["schema"])
            summary = operation.get("summary", "").replace("*/", "*\\/")
            entries.append(
                f"  /** {summary} */\n"
                f"  {op_id}: {{\n"
                f"    method: {json.dumps(method.upper())};\n"
                f"    path: {json.dumps(path)};\n"
                f"    pathParams: {_params(operation, 'path')};\n"
                f"    query: {_params(operation, 'query')};\n"
                f"    body: {body};\n"
                f"    response: {response};\n"
                f"    success: {status};\n"
                "  };"
            )
            auth = "session" if operation.get("security") else "public"
            routes.append(
                f"  {op_id}: {{ method: {json.dumps(method.upper())}, path: {json.dumps(path)}, "
                f"status: {json.dumps(operation.get('x-vyron-status', 'implemented'))}, auth: {json.dumps(auth)}, "
                f"success: {status}, tag: {json.dumps((operation.get('tags') or [''])[0])} }},"
            )
    return (
        "export interface Operations {\n" + "\n".join(entries) + "\n}\n\n"
        "export type OperationId = keyof Operations;\n\n"
        "export interface RouteInfo {\n"
        "  readonly method: \"GET\" | \"POST\" | \"PUT\" | \"DELETE\";\n"
        "  readonly path: string;\n"
        "  readonly status: \"implemented\" | \"planned\";\n"
        "  readonly auth: \"public\" | \"session\";\n"
        "  readonly success: number;\n"
        "  readonly tag: string;\n"
        "}\n\n"
        "/** Every operation in the contract. `planned` routes answer 501 until they are built. */\n"
        "export const routes = {\n" + "\n".join(routes) + "\n} as const satisfies Record<OperationId, RouteInfo>;\n"
    )


def render_typescript(spec: dict[str, Any]) -> str:
    info = spec["info"]
    header = f"// {HEADER}\n// Contract: {info['title']} {info['version']} (OpenAPI {spec['openapi']})\n\n"
    schemas = "\n".join(render_schema(name, schema) for name, schema in spec["components"]["schemas"].items())
    return header + schemas + "\n" + render_operations(spec)


def load_spec(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))
