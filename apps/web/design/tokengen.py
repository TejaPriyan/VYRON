"""Render design/tokens.json as CSS custom properties and a typed TypeScript module.

Pure functions, standard library only. ``scripts/generate_design_tokens.py`` writes the files;
``tests/test_design_contract.py`` checks they are current.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
TOKENS_PATH = HERE / "tokens.json"
PREFIX = "--vy"
HEADER = "GENERATED by scripts/generate_design_tokens.py from apps/web/design/tokens.json. Do not edit."


def load_tokens(path: Path = TOKENS_PATH) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def kebab(name: str) -> str:
    """camelCase / snake_case -> kebab-case, e.g. ``dossierWidth`` -> ``dossier-width``."""
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name).replace("_", "-")
    return spaced.lower()


def css_variables(tokens: dict[str, Any]) -> list[tuple[str, str]]:
    """Every custom property as ``(name, value)`` in a stable order."""
    out: list[tuple[str, str]] = []

    def add(path: str, value: Any) -> None:
        out.append((f"{PREFIX}-{path}", str(value)))

    for section, entries in tokens["color"].items():
        for name, value in entries.items():
            add(f"color-{section}-{kebab(name)}", value)

    data = tokens["data"]
    for group in data["groupOrder"]:
        add(f"data-{kebab(group)}", data["groups"][group]["color"])

    for name, value in tokens["type"]["families"].items():
        add(f"font-{kebab(name)}", value)
    for role, spec in tokens["type"]["roles"].items():
        role_name = kebab(role)
        add(f"type-{role_name}-size", spec["size"])
        add(f"type-{role_name}-line", spec["line"])
        add(f"type-{role_name}-weight", spec["weight"])
        add(f"type-{role_name}-tracking", spec["tracking"])

    for key in ("space", "radius", "border", "target"):
        for name, value in tokens[key].items():
            add(f"{key}-{kebab(name)}", value)

    for name, value in tokens["motion"]["duration"].items():
        add(f"motion-{kebab(name)}", value)
    for name, value in tokens["motion"]["easing"].items():
        add(f"ease-{kebab(name)}", value)
    for name, value in tokens["breakpoint"].items():
        add(f"breakpoint-{kebab(name)}", value)
    for name, value in tokens["layer"].items():
        add(f"layer-{kebab(name)}", value)
    for name, value in tokens["layout"].items():
        add(f"layout-{kebab(name)}", value)
    return out


def render_css(tokens: dict[str, Any]) -> str:
    variables = css_variables(tokens)
    lines = [f"/* {HEADER} */", ":root {", f"  color-scheme: {tokens['theme']['colorScheme']};"]
    lines += [f"  {name}: {value};" for name, value in variables]
    lines.append("}")
    # Reduced motion is part of the token contract: every duration collapses, none is left to components.
    lines += ["", "@media (prefers-reduced-motion: reduce) {", "  :root {"]
    lines += [f"    {PREFIX}-motion-{kebab(name)}: 0ms;" for name in tokens["motion"]["duration"]]
    lines += ["  }", "}"]
    # Touch targets grow on coarse pointers.
    lines += [
        "",
        "@media (pointer: coarse) {",
        "  :root {",
        f"    {PREFIX}-target-fine-pointer: var({PREFIX}-target-coarse-pointer);",
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


def _ts_literal(value: Any) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False)


def render_typescript(tokens: dict[str, Any]) -> str:
    data = tokens["data"]
    picked = {
        "color": tokens["color"],
        "groups": data["groups"],
        "groupOrder": data["groupOrder"],
        "shapes": data["shapes"],
        "kinds": data["kinds"],
        "provenance": tokens["provenance"]["kinds"],
        "provenanceStyles": tokens["provenance"]["styles"],
        "type": tokens["type"],
        "breakpoint": tokens["breakpoint"],
        "layout": tokens["layout"],
        "budget": {k: v for k, v in tokens["budget"].items() if k != "note"},
    }
    indent = "\n  "
    body = ",\n".join(f"  {key}: {_ts_literal(value).replace(chr(10), indent)}" for key, value in picked.items())
    return f"""// {HEADER}

export const tokens = {{
{body},
}} as const;

export type EntityKindKey = keyof typeof tokens.kinds;
export type DataGroupKey = (typeof tokens.groupOrder)[number];
export type ShapeKey = (typeof tokens.shapes)[number];
export type ProvenanceKey = keyof typeof tokens.provenance;
export type ProvenanceStyleKey = keyof typeof tokens.provenanceStyles;

/** The group, shape and label that draw an entity kind. Total over EntityKindKey. */
export function kindVisual(kind: EntityKindKey) {{
  const spec = tokens.kinds[kind];
  const group = tokens.groups[spec.group];
  return {{ group: spec.group, shape: spec.shape, label: spec.label, color: group.color, groupLabel: group.label }};
}}

/** How a provenance label is drawn: its words, line style and icon. Total over ProvenanceKey. */
export function provenanceVisual(provenance: ProvenanceKey) {{
  const spec = tokens.provenance[provenance];
  const style = tokens.provenanceStyles[spec.style];
  return {{ label: spec.label, icon: spec.icon, styleClass: spec.style, dash: style.dash, outline: style.outline }};
}}
"""
