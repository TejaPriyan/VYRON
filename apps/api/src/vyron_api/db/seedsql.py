"""Render the development seed as re-runnable SQL (INSERT ... ON CONFLICT DO NOTHING).

SEED DATA, NOT PRODUCTION FACTS: every row carries provenance 'seed'. The SQL is generated from the
same Python seed the in-memory tests use, so the two cannot drift; a test checks the committed file
equals this output.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence

from vyron_api.domain.entities import Entity, EntityKind
from vyron_api.seed.dev_seed import (
    SEED_NOTICE,
    relationship_id,
    seed_entities,
    seed_relationships,
    seed_timeline,
)

_TECH_KINDS = {
    EntityKind.TECHNOLOGY,
    EntityKind.FRAMEWORK,
    EntityKind.LIBRARY,
    EntityKind.DATABASE,
    EntityKind.PLATFORM,
    EntityKind.API,
}
_ORG_KINDS = {EntityKind.COMPANY, EntityKind.ORGANIZATION}


def quote(value: str) -> str:
    if "\x00" in value:
        raise ValueError("NUL characters cannot appear in SQL text")
    return "'" + value.replace("'", "''") + "'"


def _insert(table: str, columns: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    values = ",\n".join("    (" + ", ".join(row) + ")" for row in rows)
    return f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n{values}\nON CONFLICT DO NOTHING;"


def render_seed_sql() -> str:
    entities = seed_entities()
    relationships = seed_relationships()
    events = seed_timeline()

    def of_kinds(kinds: set[EntityKind]) -> list[Entity]:
        return [e for e in entities if e.kind in kinds]

    blocks = [
        f"-- {SEED_NOTICE}\n"
        "-- Generated by scripts/generate_seed_sql.py from apps/api/src/vyron_api/seed/dev_seed.py.\n"
        "-- Do not edit by hand. Safe to re-run. Never load into a production database.",
        "BEGIN;",
        _insert(
            "entities",
            ("id", "kind", "slug", "name", "provenance"),
            [
                (quote(e.id), quote(e.kind.value), quote(e.slug), quote(e.name), quote(e.provenance.value))
                for e in entities
            ],
        ),
        _insert(
            "technologies",
            ("entity_id", "kind"),
            [(quote(e.id), quote(e.kind.value)) for e in of_kinds(_TECH_KINDS)],
        ),
        _insert(
            "languages",
            ("entity_id",),
            [(quote(e.id),) for e in of_kinds({EntityKind.LANGUAGE})],
        ),
        _insert(
            "organizations",
            ("entity_id", "kind"),
            [(quote(e.id), quote(e.kind.value)) for e in of_kinds(_ORG_KINDS)],
        ),
        _insert(
            "entity_aliases",
            ("entity_id", "alias"),
            [(quote(e.id), quote(alias)) for e in entities for alias in e.aliases],
        ),
        _insert(
            "relationships",
            ("id", "source_entity_id", "target_entity_id", "relation_type", "provenance"),
            [
                (
                    quote(relationship_id(r.source_id, r.type, r.target_id)),
                    quote(r.source_id),
                    quote(r.target_id),
                    quote(r.type.value),
                    quote(r.provenance.value),
                )
                for r in relationships
            ],
        ),
        _insert(
            "timeline_events",
            (
                "id", "entity_id", "occurred_on", "date_precision", "title", "event_type",
                "provenance", "is_prediction",
            ),  # fmt: skip
            [
                (
                    quote(ev.id),
                    quote(ev.entity_id),
                    quote(ev.occurred_on.isoformat()),
                    quote(ev.precision.value),
                    quote(ev.title),
                    quote(ev.event_type),
                    quote(ev.provenance.value),
                    "true" if ev.is_prediction else "false",
                )
                for ev in events
            ],
        ),
        "COMMIT;",
    ]
    return "\n\n".join(blocks) + "\n"
